export function translate(value: string, language: Language): string {
  if (language === "en") return value;
  const trimmed = value.trim();
  const translated = zh[trimmed];
  if (!translated) return value;
  return value.replace(trimmed, translated);
}

export function applyLanguage(root: HTMLElement, language: Language, originals: WeakMap<Node, { original: string; translated: string }>) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const current = node.textContent || "";
    let entry = originals.get(node);
    if (!entry) { entry = { original: current, translated: current }; originals.set(node, entry); }
    else if (current !== entry.translated) { entry.original = current; }
    const next = translate(entry.original, language);
    if (current !== next) node.textContent = next;
    entry.translated = next;
  }
  const elements = root.querySelectorAll<HTMLElement>("*");
  for (const element of elements) {
    for (const attr of ["placeholder", "title", "aria-label"]) {
      const current = element.getAttribute(attr);
      // Keep the source text in a real data-* attribute. DOMStringMap keys
      // cannot contain hyphens (for example, dataset["i18naria-label"]).
      const originalAttribute = `data-i18n-original-${attr}`;
      let original = element.getAttribute(originalAttribute);
      if (current && original === null) {
        original = current;
        element.setAttribute(originalAttribute, original);
      }
      if (original !== null) {
        const next = translate(original, language);
        if (current !== next) element.setAttribute(attr, next);
      }
    }
  }
}
